BEGIN;
CREATE SCHEMA IF NOT EXISTS online_judge;

-- 1. Tai khoan: nguoi hoc, giang vien, quan tri dich vu cham
CREATE TABLE IF NOT EXISTS online_judge.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL CHECK (length(btrim(full_name)) > 0),
    email VARCHAR(200) NOT NULL UNIQUE CHECK (email = lower(btrim(email))),
    password_hash TEXT NOT NULL CHECK (length(password_hash) >= 20),
    role VARCHAR(12) NOT NULL DEFAULT 'student'
         CHECK (role IN ('student','lecturer','admin')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. Chu de va ngon ngu
CREATE TABLE IF NOT EXISTS online_judge.topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description TEXT
);

CREATE TABLE IF NOT EXISTS online_judge.languages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    version_label VARCHAR(80) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. Bai tap va phien ban noi dung
CREATE TABLE IF NOT EXISTS online_judge.problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    topic_id BIGINT REFERENCES online_judge.topics(id) ON DELETE SET NULL,
    difficulty VARCHAR(10) NOT NULL CHECK (difficulty IN ('easy','medium','hard')),
    created_by BIGINT REFERENCES online_judge.users(id) ON DELETE SET NULL,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS online_judge.problem_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES online_judge.problems(id) ON DELETE CASCADE,
    version_no INTEGER NOT NULL CHECK (version_no >= 1),
    statement TEXT NOT NULL,
    input_format TEXT NOT NULL,
    output_format TEXT NOT NULL,
    constraints_text TEXT,
    time_limit_ms INTEGER NOT NULL DEFAULT 1000
        CHECK (time_limit_ms BETWEEN 100 AND 30000),
    memory_limit_mb INTEGER NOT NULL DEFAULT 256
        CHECK (memory_limit_mb BETWEEN 16 AND 2048),
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (problem_id, version_no),
    UNIQUE (id, problem_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_oj_current_problem_version
    ON online_judge.problem_versions(problem_id) WHERE is_current;

-- 4. Bo du lieu test, ho tro nhieu version
CREATE TABLE IF NOT EXISTS online_judge.test_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_version_id BIGINT NOT NULL REFERENCES online_judge.problem_versions(id) ON DELETE CASCADE,
    version_no INTEGER NOT NULL CHECK (version_no >= 1),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT REFERENCES online_judge.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (problem_version_id, version_no),
    UNIQUE (id, problem_version_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_oj_active_test_set
    ON online_judge.test_sets(problem_version_id) WHERE is_active;

CREATE TABLE IF NOT EXISTS online_judge.test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_set_id BIGINT NOT NULL REFERENCES online_judge.test_sets(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position >= 1),
    input_data TEXT NOT NULL,
    expected_output TEXT NOT NULL,
    is_sample BOOLEAN NOT NULL DEFAULT FALSE,
    weight INTEGER NOT NULL DEFAULT 1 CHECK (weight >= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (test_set_id, position),
    UNIQUE (id, test_set_id)
);

-- 5. Bai nop: luu nguon va phien ban de dang tai thoi diem nop
CREATE TABLE IF NOT EXISTS online_judge.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES online_judge.users(id),
    problem_id BIGINT NOT NULL REFERENCES online_judge.problems(id),
    problem_version_id BIGINT NOT NULL,
    language_id BIGINT NOT NULL REFERENCES online_judge.languages(id),
    source_code TEXT NOT NULL CHECK (length(source_code) BETWEEN 1 AND 200000),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (problem_version_id, problem_id)
        REFERENCES online_judge.problem_versions(id, problem_id),
    UNIQUE (id, problem_version_id)
);

-- 6. Moi lan cham / cham lai. Khong gop Compile Error voi System Error.
CREATE TABLE IF NOT EXISTS online_judge.judging_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL,
    problem_version_id BIGINT NOT NULL,
    test_set_id BIGINT NOT NULL,
    attempt_no INTEGER NOT NULL DEFAULT 1 CHECK (attempt_no >= 1),
    reason VARCHAR(12) NOT NULL DEFAULT 'original'
        CHECK (reason IN ('original','rejudge')),
    verdict VARCHAR(30) NOT NULL DEFAULT 'queued'
        CHECK (verdict IN (
            'queued','running','accepted','wrong_answer','compile_error',
            'runtime_error','time_limit_exceeded','memory_limit_exceeded',
            'system_error'
        )),
    score NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 100),
    compile_log TEXT,
    system_message TEXT,
    requested_by BIGINT REFERENCES online_judge.users(id) ON DELETE SET NULL,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (submission_id, problem_version_id)
        REFERENCES online_judge.submissions(id, problem_version_id) ON DELETE CASCADE,
    FOREIGN KEY (test_set_id, problem_version_id)
        REFERENCES online_judge.test_sets(id, problem_version_id),
    UNIQUE (submission_id, attempt_no),
    UNIQUE (id, test_set_id)
);

-- 7. Ket qua tung test. FK kep dam bao case thuoc dung bo test cua lan cham.
CREATE TABLE IF NOT EXISTS online_judge.case_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judging_run_id BIGINT NOT NULL,
    test_set_id BIGINT NOT NULL,
    test_case_id BIGINT NOT NULL,
    verdict VARCHAR(30) NOT NULL CHECK (verdict IN (
        'accepted','wrong_answer','runtime_error','time_limit_exceeded',
        'memory_limit_exceeded','system_error','skipped'
    )),
    actual_output TEXT,
    stderr_output TEXT,
    execution_time_ms INTEGER CHECK (execution_time_ms >= 0),
    memory_used_kb INTEGER CHECK (memory_used_kb >= 0),
    awarded_weight INTEGER NOT NULL DEFAULT 0 CHECK (awarded_weight >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (judging_run_id, test_set_id)
        REFERENCES online_judge.judging_runs(id, test_set_id) ON DELETE CASCADE,
    FOREIGN KEY (test_case_id, test_set_id)
        REFERENCES online_judge.test_cases(id, test_set_id),
    UNIQUE (judging_run_id, test_case_id)
);

-- 8. Hang doi gui toi worker an toan, KHONG thuc thi ma nguon trong PHP Web.
CREATE TABLE IF NOT EXISTS online_judge.judge_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judging_run_id BIGINT NOT NULL UNIQUE
        REFERENCES online_judge.judging_runs(id) ON DELETE CASCADE,
    status VARCHAR(12) NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued','claimed','done','failed')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    worker_name VARCHAR(120),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    claimed_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);

-- 9. Bai giai chuan / bai sai de doi chieu bo test (CHI giang vien va admin duoc xem).
CREATE TABLE IF NOT EXISTS online_judge.reference_solutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_version_id BIGINT NOT NULL
        REFERENCES online_judge.problem_versions(id) ON DELETE CASCADE,
    language_id BIGINT NOT NULL REFERENCES online_judge.languages(id),
    solution_kind VARCHAR(10) NOT NULL CHECK (solution_kind IN ('correct','incorrect')),
    source_code TEXT NOT NULL,
    note TEXT,
    UNIQUE (problem_version_id, language_id, solution_kind)
);

-- Index phuc vu danh sach, lich su va thong ke
CREATE INDEX IF NOT EXISTS idx_oj_problems_topic
    ON online_judge.problems(topic_id, difficulty);
CREATE INDEX IF NOT EXISTS idx_oj_versions_problem
    ON online_judge.problem_versions(problem_id);
CREATE INDEX IF NOT EXISTS idx_oj_cases_set
    ON online_judge.test_cases(test_set_id, position);
CREATE INDEX IF NOT EXISTS idx_oj_submissions_student
    ON online_judge.submissions(student_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_oj_submissions_problem
    ON online_judge.submissions(problem_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_oj_runs_submission
    ON online_judge.judging_runs(submission_id, attempt_no DESC);
CREATE INDEX IF NOT EXISTS idx_oj_case_results_run
    ON online_judge.case_results(judging_run_id);
CREATE INDEX IF NOT EXISTS idx_oj_jobs_status
    ON online_judge.judge_jobs(status, created_at);

-- View CHI cong bo cac test danh dau la vi du.
CREATE OR REPLACE VIEW online_judge.v_public_examples AS
SELECT p.id AS problem_id, p.slug, pv.version_no,
       tc.position, tc.input_data, tc.expected_output
FROM online_judge.problems p
JOIN online_judge.problem_versions pv ON pv.problem_id = p.id AND pv.is_current
JOIN online_judge.test_sets ts ON ts.problem_version_id = pv.id AND ts.is_active
JOIN online_judge.test_cases tc ON tc.test_set_id = ts.id AND tc.is_sample
WHERE p.is_published;

-- View lich su: moi bai nop chi lay ket qua cham MOI NHAT.
CREATE OR REPLACE VIEW online_judge.v_submission_latest AS
SELECT s.id AS submission_id, s.student_id, s.problem_id,
       p.title AS problem_title, l.name AS language_name,
       s.submitted_at, j.id AS judging_run_id,
       COALESCE(j.verdict, 'queued') AS verdict,
       COALESCE(j.score, 0)::NUMERIC(5,2) AS score,
       j.attempt_no, j.finished_at
FROM online_judge.submissions s
JOIN online_judge.problems p ON p.id = s.problem_id
JOIN online_judge.languages l ON l.id = s.language_id
LEFT JOIN LATERAL (
    SELECT r.id, r.verdict, r.score, r.attempt_no, r.finished_at
    FROM online_judge.judging_runs r
    WHERE r.submission_id = s.id
    ORDER BY r.attempt_no DESC
    LIMIT 1
) j ON TRUE;

CREATE OR REPLACE VIEW online_judge.v_student_progress AS
SELECT student_id, problem_id, COUNT(*)::INTEGER AS submission_count,
       COUNT(*) FILTER (WHERE verdict = 'accepted')::INTEGER AS accepted_count,
       MAX(score) AS best_score,
       MAX(submitted_at) AS last_submitted_at
FROM online_judge.v_submission_latest
GROUP BY student_id, problem_id;

CREATE OR REPLACE VIEW online_judge.v_problem_stats AS
SELECT p.id AS problem_id, p.title, p.difficulty,
       COUNT(v.submission_id)::INTEGER AS total_submissions,
       COUNT(DISTINCT v.student_id)::INTEGER AS participants,
       COUNT(v.submission_id) FILTER (WHERE v.verdict = 'accepted')::INTEGER AS accepted_submissions
FROM online_judge.problems p
LEFT JOIN online_judge.v_submission_latest v ON v.problem_id = p.id
GROUP BY p.id, p.title, p.difficulty;

